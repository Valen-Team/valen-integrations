"""Write tools/<tool>.py: one self-contained file per Coze IDE tool, from src/common.py and src/<tool>.py."""
from pathlib import Path
import argparse

HERE = Path(__file__).parent
TOOLS = ("yes_no", "choice", "score", "evaluate")
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()

common = (HERE / "src/protocol.py").read_text() + "\n\n" + (HERE / "src/common.py").read_text()
for tool in TOOLS:
    header = f'"""Valen for Coze: the {tool} tool. Generated by coze/build.py from coze/src; edit the sources there."""\n'
    body = (HERE / f"src/{tool}.py").read_text()
    generated = header + common.replace("typings.TOOL.TOOL", f"typings.{tool}.{tool}") + "\n\n" + body
    target = HERE / f"tools/{tool}.py"
    if args.check:
        if not target.exists() or target.read_text() != generated:
            raise SystemExit(f'Stale generated Coze tool: {tool}')
    else:
        target.write_text(generated)
